"""Output writers for rice-palette: tokens -> quickshell / kitty / hyprland / btop files.

Pure standard library. See spec section 5.4.
"""
import json
import re

from palette import _lift, hex_to_oklch

_HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def roles_from_matugen(doc):
    """Pull the dark primary/tertiary colours out of `matugen --json hex` output."""
    if not isinstance(doc, dict):
        raise ValueError("matugen output is not a JSON object")
    roles = {}
    for name in ("primary", "tertiary"):
        try:
            value = doc["colors"][name]["dark"]["color"]
        except (KeyError, TypeError):
            raise ValueError(f"matugen output has no .colors.{name}.dark.color") from None
        if not isinstance(value, str) or not _HEX.match(value):
            raise ValueError(f".colors.{name}.dark.color is not a #rrggbb colour: {value!r}")
        roles[name] = value
    return roles


def render_quickshell(tokens):
    keys = ("bg", "panel", "line", "dim", "fg", "a1", "a2", "warn")
    return json.dumps({k: tokens[k] for k in keys}, indent=2) + "\n"


def _kitty_color8(tokens):
    """dim, lifted if needed so bright-black text keeps 4.5:1 on bg."""
    l, c, h = hex_to_oklch(tokens["dim"])
    return _lift(l, c, h, tokens["bg"], 4.5)


# ANSI slots with no token of their own keep fixed hues (they are not wallpaper-derived).
_KITTY_FIXED = {
    2: "#3dff9a", 4: "#5c8cff", 5: "#c77dff", 9: "#ff6aa8", 10: "#7dffb8",
    11: "#ffe27a", 12: "#8fb0ff", 13: "#dca0ff", 14: "#7ffaff", 15: "#ffffff",
}


def render_kitty(tokens):
    t = tokens
    pairs = [
        ("foreground", t["fg"]), ("background", t["bg"]), ("cursor", t["a1"]),
        ("cursor_text_color", t["bg"]), ("selection_foreground", t["bg"]),
        ("selection_background", t["a1"]), ("active_border_color", t["a1"]),
        ("inactive_border_color", t["line"]),
    ]
    ansi = {0: t["panel"], 1: t["a2"], 3: t["warn"], 6: t["a1"], 7: t["fg"],
            8: _kitty_color8(t), **_KITTY_FIXED}
    pairs += [(f"color{i}", ansi[i]) for i in range(16)]
    return "# generated by rice-palette\n" + "".join(f"{k:<22}{v}\n" for k, v in pairs)


def _kitty_pairs(text):
    """Parse a kitty colour file into {key: value}, ignoring comments and whitespace."""
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            k, v = line.split(None, 1)
            out[k] = v.strip().lower()
    return out


def render_hypr(tokens):
    a1, a2, line = (tokens[k].lstrip("#") for k in ("a1", "a2", "line"))
    return ("-- generated by rice-palette\n"
            "return {\n"
            f'    active = {{ "rgba({a1}ff)", "rgba({a2}ff)" }},\n'
            f'    inactive = "rgba({line}ff)",\n'
            "}\n")


def hypr_border_lua(tokens):
    """The Lua that `hyprctl eval` runs to recolour the borders of a running session.

    The same colours as render_hypr (and hyprland.lua's col block), set at runtime so
    nothing has to reload the config (a reload re-applies the monitor lines and would
    light a panel the lid script disabled).
    """
    a1, a2, line = (tokens[k].lstrip("#") for k in ("a1", "a2", "line"))
    return ("hl.config({ general = { col = { "
            f'active_border = {{ colors = {{ "rgba({a1}ff)", "rgba({a2}ff)" }}, angle = 45 }}, '
            f'inactive_border = "rgba({line}ff)" }} }} }})')


def _mix(a, b, f):
    ca = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    cb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join("%02x" % round(x + (y - x) * f) for x, y in zip(ca, cb))


def render_btop(tokens):
    t = tokens
    theme = {
        "main_bg": t["bg"], "main_fg": t["fg"], "title": t["fg"], "hi_fg": t["a1"],
        "selected_bg": t["line"], "selected_fg": t["a1"], "inactive_fg": t["dim"],
        "graph_text": t["dim"], "meter_bg": t["line"], "proc_misc": t["a2"],
        "cpu_box": t["a1"], "mem_box": t["a2"], "net_box": t["a1"], "proc_box": t["a2"],
        "div_line": t["line"],
    }
    # (start, end) per graph; mid is the halfway mix (temp passes through warn).
    grads = {
        "temp": (t["a1"], t["a2"]), "cpu": (t["a1"], t["a2"]), "free": (t["dim"], t["a1"]),
        "cached": (t["dim"], t["a2"]), "available": (t["dim"], t["a1"]),
        "used": (t["a1"], t["a2"]), "download": (t["a1"], t["fg"]),
        "upload": (t["a2"], t["fg"]), "process": (t["a1"], t["a2"]),
    }
    for name, (start, end) in grads.items():
        theme[f"{name}_start"] = start
        theme[f"{name}_mid"] = t["warn"] if name == "temp" else _mix(start, end, 0.5)
        theme[f"{name}_end"] = end
    return "# generated by rice-palette\n" + "".join(
        f'theme[{k}]="{v}"\n' for k, v in theme.items())
