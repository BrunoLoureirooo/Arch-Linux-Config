#!/usr/bin/env bash
# Fetch quickshell, matugen, wev, wtype (Arch mirror packages) and xremap (GitHub
# release) into ~/.cache/rice-testbin without root. Idempotent: re-running only
# fetches what is missing.
set -euo pipefail

TB="${RICE_TESTBIN:-$HOME/.cache/rice-testbin}"
PKG="$TB/pkg"
ROOT="$TB/root"
XREMAP_VER="v0.15.15"
XREMAP_ASSET="xremap-linux-x86_64-hypr.zip"
SHELLCHECK_VER="v0.11.0"

die() { echo "setup-testbin: $*" >&2; exit 1; }

fetch() { # url dest
    [[ -s "$2" ]] && return 0
    echo "fetch $1"
    curl -fsSL --retry 3 -o "$2.part" "$1" || die "download failed: $1"
    mv "$2.part" "$2"
}

mkdir -p "$PKG" "$ROOT/usr/bin" "$TB/xremap" "$TB/shellcheck"

# 1. Arch packages. `pacman -Sp` prints URLs (missing deps included), no root needed.
#    labwc (wlroots) is the invisible headless parent compositor for the rig; it is
#    used because it offers xdg_wm_base v6, which Aquamarine requires (cage/sway
#    offer only v5).
mapfile -t urls < <(pacman -Sp quickshell matugen wev wtype labwc)
[[ ${#urls[@]} -gt 0 ]] || die "pacman -Sp returned no URLs"
for u in "${urls[@]}"; do
    [[ "$u" == http* ]] || die "unexpected pacman -Sp output: $u"
    name="${u##*/}"
    f="$PKG/$name"
    if [[ ! -s "$f" ]] && ! curl -fsIL -o /dev/null "$u"; then
        # Local sync db older than the mirror: the exact version lives on the archive.
        pkgname=$(sed -E 's/-[^-]+-[^-]+-[^-]+\.pkg\.tar\.zst$//' <<<"$name")
        u="https://archive.archlinux.org/packages/${pkgname:0:1}/$pkgname/$name"
    fi
    fetch "$u" "$f"
    if [[ ! -e "$f.extracted" ]]; then
        bsdtar -xf "$f" -C "$ROOT" --exclude '.PKGINFO' --exclude '.BUILDINFO' \
            --exclude '.MTREE' --exclude '.INSTALL'
        touch "$f.extracted"
    fi
done
# Packages ship absolute symlinks (qs -> /usr/bin/quickshell); point them into ROOT.
ln -sfn quickshell "$ROOT/usr/bin/qs"

# 2. xremap built with Hyprland support (used only to check that configs parse).
fetch "https://github.com/xremap/xremap/releases/download/$XREMAP_VER/$XREMAP_ASSET" \
    "$TB/xremap/$XREMAP_ASSET"
if [[ ! -x "$ROOT/usr/bin/xremap" ]]; then
    bsdtar -xf "$TB/xremap/$XREMAP_ASSET" -C "$TB/xremap"
    install -m755 "$TB/xremap/xremap" "$ROOT/usr/bin/xremap"
fi

# 3. Static shellcheck to lint the rig scripts (dev tool only).
sc_tar="shellcheck-$SHELLCHECK_VER.linux.x86_64.tar.xz"
fetch "https://github.com/koalaman/shellcheck/releases/download/$SHELLCHECK_VER/$sc_tar" \
    "$TB/shellcheck/$sc_tar"
if [[ ! -x "$ROOT/usr/bin/shellcheck" ]]; then
    bsdtar -xf "$TB/shellcheck/$sc_tar" -C "$TB/shellcheck"
    install -m755 "$TB/shellcheck/shellcheck-$SHELLCHECK_VER/shellcheck" "$ROOT/usr/bin/shellcheck"
fi

# 4. env.sh
cat > "$TB/env.sh" <<ENV
# Generated by tests/rig/setup-testbin.sh. Source it, do not execute it.
export RICE_TESTBIN="$TB"
export PATH="$ROOT/usr/bin:\$PATH"
export LD_LIBRARY_PATH="$ROOT/usr/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export QT_PLUGIN_PATH="$ROOT/usr/lib/qt6/plugins:/usr/lib/qt6/plugins"
export QML_IMPORT_PATH="$ROOT/usr/lib/qt6/qml:/usr/lib/qt6/qml"
export QML2_IMPORT_PATH="\$QML_IMPORT_PATH"
ENV

# 5. Record the live Hyprland instance(s) so rig guards can refuse them: every
#    instance dir whose hyprland.lock PID is a running Hyprland that was not started
#    by the rig (rig processes carry RICE_RIG_ID in their environment).
hypr_run="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/hypr"
live=""
for d in "$hypr_run"/*/; do
    [[ -f "$d/hyprland.lock" ]] || continue
    pid=$(head -n 1 "$d/hyprland.lock")
    [[ "$pid" =~ ^[0-9]+$ ]] || continue
    [[ "$(cat "/proc/$pid/comm" 2>/dev/null)" == Hyprland ]] || continue
    if tr '\0' '\n' 2>/dev/null <"/proc/$pid/environ" | grep -q '^RICE_RIG_ID='; then
        continue
    fi
    sig=$(basename "$d")
    live+="$sig"$'\n'
done
live="${live%$'\n'}"
if [[ -n "$live" ]]; then
    printf '%s\n' "$live" > "$TB/live.sig"
elif [[ ! -s "$TB/live.sig" ]]; then
    echo "setup-testbin: warning: no live Hyprland instance found to record" >&2
fi

# 6. Verify.
# shellcheck source=/dev/null
source "$TB/env.sh"
unset WAYLAND_DISPLAY HYPRLAND_INSTANCE_SIGNATURE
for b in qs matugen wev wtype xremap labwc; do
    [[ -x "$ROOT/usr/bin/$b" ]] || die "$b missing from $ROOT/usr/bin"
    missing=$(ldd "$ROOT/usr/bin/$b" | grep 'not found' || true)
    [[ -z "$missing" ]] || die "$b has missing libraries: $missing"
done
echo "== qs --version";      qs --version
echo "== matugen --version"; matugen --version
echo "== wev -h";            wev -h 2>&1 | head -n 3 || true
echo "== wtype (usage)";     wtype 2>&1 | head -n 3 || true
echo "== xremap --help";     { xremap --help | head -n 1; } || true; xremap --version
echo "== shellcheck";        shellcheck --version | sed -n 2p
echo "== live.sig";          cat "$TB/live.sig" 2>/dev/null || echo "(none)"
echo "setup-testbin: OK ($TB)"
